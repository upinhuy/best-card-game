// random.js — small seeded random generator for Duel Arkanum.
// One job: deterministic shuffles and draws from a numeric seed, so a
// screenshot or a replay can rebuild the exact same deck order.

export function mulberry32(seed) {
  let a = seed >>> 0;
  return function next() {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Fisher-Yates shuffle that consumes the given rng in a fixed order.
export function shuffle(deck, rng) {
  const out = deck.slice();
  for (let i = out.length - 1; i > 0; i -= 1) {
    const j = Math.floor(rng() * (i + 1));
    const tmp = out[i];
    out[i] = out[j];
    out[j] = tmp;
  }
  return out;
}

// Pick an integer in [0, n) from the rng.
export function pickInt(rng, n) {
  return Math.floor(rng() * n);
}
